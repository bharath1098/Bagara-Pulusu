export function imageForMenuItem(name: string, _category: string): string {
  const key = name.trim().toLowerCase();
  if (key === "bagara" || key.includes("bagara rice")) {
    return CAFE_MEDIA.bagaraRice;
  }
  if (key === "white rice" || key === "plain rice" || key === "steamed rice") {
    return CAFE_MEDIA.whiteRice;
  }
  if (
    key === "zeera rice" ||
    key === "jeera rice" ||
    key.includes("zeera") ||
    key.includes("jeera")
  ) {
    return CAFE_MEDIA.zeeraRice;
  }
  if (key.includes("chicken") && key.includes("pulao")) {
    return CAFE_MEDIA.chickenPulao;
  }
  if (key === "pulao" || key === "veg pulao" || key.includes("pulao")) {
    return CAFE_MEDIA.vegPulao;
  }
  if (key === "curd rice" || key.includes("curd rice") || key === "thayir sadam") {
    return CAFE_MEDIA.curdRice;
  }
  if (
    key.includes("ambar") ||
    key.includes("amber") ||
    key === "chicken sambar rice" ||
    (key.includes("sambar") && key.includes("chicken"))
  ) {
    return CAFE_MEDIA.chickenAmbarRice;
  }
  if (
    key === "sambar rice" ||
    key === "veg sambar rice" ||
    (key.includes("sambar") && key.includes("rice"))
  ) {
    return CAFE_MEDIA.vegSambarRice;
  }
  if (
    key.includes("muddapappu") ||
    key.includes("avakaya") ||
    key === "mudda pappu avakaya"
  ) {
    return CAFE_MEDIA.muddapappuAvakaya;
  }
  if (key.includes("chicken") && key.includes("biryani")) {
    return CAFE_MEDIA.chickenBiryani;
  }
  if (key.includes("fish") && key.includes("biryani")) {
    return CAFE_MEDIA.fishBiryani;
  }
  if (
    (key.includes("prawn") || key.includes("shrimp")) &&
    key.includes("biryani")
  ) {
    return CAFE_MEDIA.prawnsBiryani;
  }
  if (
    key === "veg biryani" ||
    (key.includes("biryani") &&
      !key.includes("chicken") &&
      !key.includes("fish") &&
      !key.includes("prawn") &&
      !key.includes("mutton"))
  ) {
    return CAFE_MEDIA.vegBiryani;
  }
  if (
    key === "dal" ||
    key === "dal curry" ||
    key === "dal tadka" ||
    key.startsWith("dal ")
  ) {
    return CAFE_MEDIA.dal;
  }
  if (
    key === "veg curry" ||
    key === "mixed veg curry" ||
    key.includes("mixed veg")
  ) {
    return CAFE_MEDIA.mixedVegCurry;
  }
  if (key === "sambar" || key === "veg sambar") {
    return CAFE_MEDIA.sambar;
  }
  if (key === "egg fry" || key.includes("egg fry")) {
    return CAFE_MEDIA.eggFry;
  }
  if (key === "chicken fry" || key.includes("chicken fry")) {
    return CAFE_MEDIA.chickenFry;
  }
  if (key === "liver fry" || key.includes("liver fry")) {
    return CAFE_MEDIA.liverFry;
  }
  if (key === "boti fry" || key.includes("boti fry")) {
    return CAFE_MEDIA.botiFry;
  }
  if (key === "boti curry" || (key.includes("boti") && key.includes("curry"))) {
    return CAFE_MEDIA.botiCurry;
  }
  if (key === "fish fry" || key.includes("fish fry")) {
    return CAFE_MEDIA.fishFry;
  }
  if (
    key === "prawns fry" ||
    key === "prawn fry" ||
    key.includes("prawns fry") ||
    key.includes("prawn fry")
  ) {
    return CAFE_MEDIA.prawnsFry;
  }
  if (
    key.includes("kaju") &&
    (key.includes("mushroom") || key.includes("curry"))
  ) {
    return CAFE_MEDIA.kajuMushroomCurry;
  }
  if (
    (key.includes("aloo") || key.includes("alu")) &&
    (key.includes("gobi") || key.includes("kurma"))
  ) {
    return CAFE_MEDIA.alooGobiKurma;
  }
  if (
    (key.includes("chilli") || key.includes("chili") || key.includes("chilly")) &&
    (key.includes("paneer") || key.includes("panner"))
  ) {
    return CAFE_MEDIA.chilliPaneer;
  }
  if (
    (key.includes("chilli") || key.includes("chili") || key.includes("chilly")) &&
    key.includes("chicken")
  ) {
    return CAFE_MEDIA.chillyChicken;
  }
  if (key.includes("chicken 65") || key.includes("chicken65")) {
    return CAFE_MEDIA.chicken65;
  }
  if (key.includes("wing")) {
    return CAFE_MEDIA.chickenWings;
  }
  if (key.includes("pepper") && key.includes("chicken")) {
    return CAFE_MEDIA.pepperChicken;
  }
  if (
    (key.includes("prawn") || key.includes("shrimp")) &&
    key.includes("loose")
  ) {
    return CAFE_MEDIA.prawnsLoose;
  }
  if (key.includes("thali") && key.includes("chicken")) {
    return CAFE_MEDIA.chickenThali;
  }
  if (key.includes("thali") && key.includes("fish")) {
    return CAFE_MEDIA.fishThali;
  }
  if (
    key.includes("thali") &&
    (key.includes("mix") || key.includes("mixed"))
  ) {
    return CAFE_MEDIA.mixThali;
  }
  if (
    key === "veg thali" ||
    (key.includes("thali") &&
      key.includes("veg") &&
      !key.includes("non"))
  ) {
    return CAFE_MEDIA.vegThali;
  }
  if (key === "pulka" || key.includes("pulka") || key.includes("phulka")) {
    return CAFE_MEDIA.pulka;
  }
  if (
    key.includes("chapathi") ||
    key.includes("chapati") ||
    key.includes("chapthi") ||
    key.includes("roti")
  ) {
    return CAFE_MEDIA.chapathi;
  }
  if (key.includes("paratha") || key.includes("parata") || key.includes("parantha")) {
    return CAFE_MEDIA.paratha;
  }
  if (key.includes("thums") || key.includes("thumsup") || key.includes("thumbs up")) {
    return CAFE_MEDIA.thumsUp;
  }
  if (key.includes("red bull") || key.includes("redbull")) {
    return CAFE_MEDIA.redBull;
  }
  if (key.includes("diet coke") || key.includes("dietcola")) {
    return CAFE_MEDIA.dietCoke;
  }
  if (
    key === "coke" ||
    key === "coca cola" ||
    key === "coca-cola" ||
    key.includes("coca cola")
  ) {
    return CAFE_MEDIA.coke;
  }
  if (key.includes("sprite")) {
    return CAFE_MEDIA.sprite;
  }
  if (key.includes("brownie")) {
    return CAFE_MEDIA.brownieIcecream;
  }
  if (
    key.includes("mineral water") ||
    key.includes("minaral water") ||
    key === "water" ||
    key.includes("bottled water")
  ) {
    return CAFE_MEDIA.mineralWater;
  }
  if (key.includes("mango") && key.includes("juice")) {
    return CAFE_MEDIA.mangoJuice;
  }
  if (
    (key.includes("watermelon") || key.includes("water melon")) &&
    key.includes("juice")
  ) {
    return CAFE_MEDIA.watermelonJuice;
  }
  if (
    (key.includes("mosambi") ||
      key.includes("mousambi") ||
      key.includes("sweet lime")) &&
    (key.includes("juice") || key === "mosambi" || key === "mousambi")
  ) {
    return CAFE_MEDIA.mosambiJuice;
  }
  if (
    (key.includes("chocolate") || key.includes("choco")) &&
    key.includes("shake")
  ) {
    return CAFE_MEDIA.chocolateShake;
  }
  if (key.includes("oreo") && key.includes("shake")) {
    return CAFE_MEDIA.oreoShake;
  }
  if (key.includes("vanilla") && key.includes("shake")) {
    return CAFE_MEDIA.vanillaShake;
  }
  if (key.includes("mango") && key.includes("shake")) {
    return CAFE_MEDIA.mangoShake;
  }
  if (key.includes("strawberry") && key.includes("shake")) {
    return CAFE_MEDIA.strawberryShake;
  }
  if (
    (key.includes("badam") || key.includes("almond")) &&
    key.includes("shake")
  ) {
    return CAFE_MEDIA.badamShake;
  }
  if (
    key === "paneer curry" ||
    key === "panner curry" ||
    ((key.includes("paneer") || key.includes("panner")) &&
      key.includes("curry"))
  ) {
    return CAFE_MEDIA.paneerCurry;
  }
  if (key === "egg curry" || (key.includes("egg") && key.includes("curry"))) {
    return CAFE_MEDIA.eggCurry;
  }
  if (
    key === "chicken curry" ||
    (key.includes("chicken") &&
      key.includes("curry") &&
      !key.includes("biryani") &&
      !key.includes("fry") &&
      !key.includes("pulao"))
  ) {
    return CAFE_MEDIA.chickenCurry;
  }
  if (
    key.includes("chepala") ||
    key.includes("chapala") ||
    (key.includes("pulusu") && key.includes("fish")) ||
    key === "chepala pulusu"
  ) {
    return CAFE_MEDIA.chepalaPulusu;
  }
  if (
    (key.includes("prawn") || key.includes("shrimp")) &&
    key.includes("curry") &&
    !key.includes("biryani") &&
    !key.includes("fry")
  ) {
    return CAFE_MEDIA.prawnsCurry;
  }
  return "";
}

export function hasImage(src?: string | null): src is string {
  return Boolean(src && src.trim().length > 0);
}
